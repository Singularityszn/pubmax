#!/usr/bin/env node

// A pool worktree keeps the slot's node_modules across checkouts, so it can
// predate package-lock.json and `npm run dev` dies on a module the lockfile
// already names. This compares the non-optional packages in package-lock.json
// with node_modules/.package-lock.json. Optional packages may be absent.
//
// It is the first command of `predev` and of `test`. When `predev` is folded
// into the `dev` script, it must stay ahead of `next dev` there.

import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const NODE_MODULES_STALE_MESSAGE =
  "node_modules is older than package-lock.json: run `npm ci`";

function readLock(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

export function installedTreeIsStale(root) {
  const required = readLock(resolve(root, "package-lock.json"));
  const installedPath = resolve(root, "node_modules", ".package-lock.json");
  if (!existsSync(installedPath)) return true;
  const installed = readLock(installedPath);
  const have = installed.packages ?? {};
  for (const [name, entry] of Object.entries(required.packages ?? {})) {
    if (name === "" || entry?.optional === true) continue;
    if (have[name]?.version !== entry?.version) return true;
  }
  return false;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    if (installedTreeIsStale(process.cwd())) {
      console.error(NODE_MODULES_STALE_MESSAGE);
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 2;
  }
}
